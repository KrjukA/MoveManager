from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={"width":1440,"height":860})
    errs=[]; pg.on("pageerror", lambda e: errs.append(str(e))); pg.on("console", lambda m: errs.append(m.text) if m.type=="error" else None)
    pg.on("dialog", lambda d: (errs.append("DIALOG: "+d.message[:70]), d.accept()))
    pg.goto("http://127.0.0.1:8765"); pg.wait_for_timeout(2500)
    pg.locator("#moveGrid .tile", has_text="Set 99").first.click(); pg.wait_for_timeout(300)
    print("cbars:", pg.locator("#moveGrid .cbar").count(), "bpm titles:", pg.evaluate("[...document.querySelectorAll('.bpm[title]')].length"))
    pg.screenshot(path="/tmp/k1.png")
    pg.locator("#libGrid .tile").first.click(); n0 = pg.locator("#libGrid .tile").count()
    pg.locator("#nameIn").focus(); pg.keyboard.press("Backspace"); pg.wait_for_timeout(300)
    print("в поле Backspace не удаляет:", pg.locator("#libGrid .tile").count()==n0)
    pg.locator("#libGrid .tile").first.click(); pg.keyboard.press("Delete"); pg.wait_for_timeout(1200)
    print("после Delete:", n0, "->", pg.locator("#libGrid .tile").count())
    print(errs); b.close()
