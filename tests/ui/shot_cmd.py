"""Разделы Projects | Samples | Presets и две панели (Move слева, компьютер или Move справа). После run_env.sh."""
import os, sys
from playwright.sync_api import sync_playwright
ok = True
def check(name, cond):
    global ok
    print(("PASS " if cond else "FAIL ") + name); ok = ok and bool(cond)
SONG = "/tmp/fakeul/Sets/aaaaaaaa-0000-0000-0000-000000000001/Seed Proj/Song.abl"
NEW = "Seed Proj - Bounce 4 - 100 bpm.wav"
with sync_playwright() as p:
    b = p.chromium.launch(args=["--autoplay-policy=no-user-gesture-required"]); pg = b.new_context(viewport={"width":1440,"height":1000}).new_page()
    errs, dialogs = [], []
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.on("dialog", lambda d: (dialogs.append(d.message), d.accept()))
    pg.goto("http://127.0.0.1:8765"); pg.wait_for_timeout(2000)
    pg.request.get("http://127.0.0.1:8765/api/fs?mode=samples&path=/root/mmpc")
    check("три раздела сверху", pg.locator("header [data-view]").count() == 3)
    check("старых переключателей в панели нет", pg.locator("[data-libmode]").count() == 0)
    pg.locator("[data-view=samples]").click(); pg.wait_for_timeout(1800)
    check("Folder… спрятан в Samples", not pg.locator("#chooseFolder").is_visible())
    L, R = pg.locator("#moveGrid"), pg.locator("#libGrid")
    check("слева Move: папки и счётчик", "1 of 2 used" in L.locator("[data-ulfolder='Samples/Bounces'] .uluse").inner_text())
    check("справа компьютер", R.locator("[data-pcfolder='/root/mmpc/Kits']").count() == 1)
    L.locator("[data-ulfolder='Samples/Bounces']").dblclick(); pg.wait_for_timeout(500)
    L.locator("[data-ulfile='Samples/Bounces/Set 93 Bounce 4 - 100 bpm.wav']").click(); pg.wait_for_timeout(300)
    check("карточка: где используется", "Seed Proj" in pg.locator("#insp").inner_text())
    pg.locator("#ulPlay").click(); pg.wait_for_timeout(120)
    check("прослушка с Move", pg.evaluate("(S.playing||'').startsWith('ul:') && !audio.error"))
    pg.wait_for_timeout(500)
    pg.locator("[data-ulsuggest]").first.click(); pg.wait_for_timeout(3000)
    check("имя по проекту + ссылки", os.path.exists("/tmp/fakeul/Samples/Bounces/" + NEW) and "Seed%20Proj%20-%20Bounce%204" in open(SONG).read())
    R.locator("[data-pcfolder='/root/mmpc/Kits']").dblclick(); pg.wait_for_timeout(600)
    check("справа только аудио", R.locator("[data-pcfile='/root/mmpc/Kits/snare.wav']").count() == 1 and R.locator("text=readme.txt").count() == 0)
    R.locator("[data-pcfile='/root/mmpc/Kits/snare.wav']").click(); pg.wait_for_timeout(300)
    pg.locator("#pcPlay").click(); pg.wait_for_timeout(120)
    check("прослушка с компьютера", pg.evaluate("(S.playing||'').startsWith('pc:') && !audio.error"))
    pg.wait_for_timeout(400)
    R.locator("[data-pcfile='/root/mmpc/Kits/snare.wav']").drag_to(L.locator("[data-ulfile='Samples/Bounces/" + NEW + "']")); pg.wait_for_timeout(2500)
    check("компьютер → Move: копия", os.path.exists("/tmp/fakeul/Samples/Bounces/snare.wav") and os.path.exists("/root/mmpc/Kits/snare.wav"))
    L.locator("[data-ulfile='Samples/Bounces/" + NEW + "']").drag_to(R.locator("[data-pcfile='/root/mmpc/Kits/snare.wav']")); pg.wait_for_timeout(2500)
    check("Move → компьютер: копия", os.path.exists("/root/mmpc/Kits/" + NEW) and os.path.exists("/tmp/fakeul/Samples/Bounces/" + NEW))
    R.locator("[data-pcfile='/root/mmpc/Kits/snare.wav']").drag_to(pg.locator(".pbar[data-panel=R] [data-act=up]")); pg.wait_for_timeout(1500)
    check("внутри компьютера: перенос", os.path.exists("/root/mmpc/snare.wav") and not os.path.exists("/root/mmpc/Kits/snare.wav"))
    pg.locator("[data-rkind=move]").click(); pg.wait_for_timeout(1500)
    check("справа можно включить Move", R.locator("[data-ulfolder='Samples/Drums']").count() == 1)
    L.locator("[data-ulfile='Samples/Bounces/" + NEW + "']").drag_to(R.locator("[data-ulfolder='Samples/Drums']")); pg.wait_for_timeout(3500)
    check("Move → Move: перенос с окном плана", any("Seed Proj" in d for d in dialogs[-1:]) and os.path.exists("/tmp/fakeul/Samples/Drums/" + NEW) and "Samples/Drums/Seed%20Proj" in open(SONG).read())
    check("левая панель обновилась", L.locator("[data-ulfile='Samples/Bounces/" + NEW + "']").count() == 0)
    pg.locator("[data-rkind=pc]").click(); pg.wait_for_timeout(800)
    pg.locator(".pbar[data-panel=L] [data-act=up]").click(); pg.wait_for_timeout(400)
    L.locator("[data-ulfolder='Samples/Drums']").dblclick(); pg.wait_for_timeout(400)
    L.locator("[data-ulfile='Samples/Drums/old unused.wav']").click(); pg.wait_for_timeout(300)
    pg.locator("#ulDelete").click(); pg.wait_for_timeout(1500)
    check("удаление неиспользуемого", not os.path.exists("/tmp/fakeul/Samples/Drums/old unused.wav"))
    pg.locator("[data-view=presets]").click(); pg.wait_for_timeout(1800)
    check("Presets: слева пресеты Move", L.locator("[data-ulfolder='Track Presets/Drums']").count() == 1)
    R.locator("[data-act=up]").count()
    pg.locator(".pbar[data-panel=R] [data-act=up]").click(); pg.wait_for_timeout(600)
    check("Presets: справа пресеты компьютера", R.locator("[data-pcfile='/root/mmpc/lead.ablpreset']").count() == 1)
    pg.locator("[data-view=projects]").click(); pg.wait_for_timeout(1200)
    check("Projects как раньше", R.locator(".tile.row").count() > 0 and L.locator(".tile").count() > 0 and pg.locator("#chooseFolder").is_visible())
    check("нет ошибок страницы", not errs); print(errs) if errs else None
    b.close()
sys.exit(0 if ok else 1)
